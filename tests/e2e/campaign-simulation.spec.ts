import { expect, test } from "@playwright/test";
const enabled = process.env.E2E_ISOLATED_AUTH === "true" && Boolean(process.env.E2E_EMAIL_C && process.env.E2E_PASSWORD_C);
test("isolated campaign simulation preserves completed interaction qualification and reset", async ({ page }) => {
  test.skip(!enabled, "Requires disposable isolated campaign fixtures.");
  await page.goto("/login"); await page.getByLabel("Email").fill(process.env.E2E_EMAIL_C!); await page.getByLabel("Password").fill(process.env.E2E_PASSWORD_C!); await page.getByRole("button", { name: /log in/i }).click(); await expect(page).toHaveURL(/dashboard/);
  await page.goto("/dashboard/campaigns"); await expect(page.getByText("Simulation Studio", { exact: false })).toBeVisible(); await expect(page.getByText(/no outbound calls/i)).toBeVisible();
  await page.getByLabel("Simulation campaign").selectOption({ label: "E2E Campaign A · draft" });
  await page.getByRole("button", { name: /run readiness check/i }).click();
  await expect(page.getByText(/Ready\. This is simulation only\./i)).toBeVisible();
  await page.getByLabel("Mock outcome").selectOption("interested");
  await page.getByRole("button", { name: /start simulation/i }).click();
  const interactionPicker = page.getByLabel("Completed interaction");
  await expect(interactionPicker).toBeVisible();
  await expect(page.getByText(/Not yet qualified/i)).toBeVisible();
  await interactionPicker.selectOption({ index: 1 });
  await expect(page.getByText(/Score: 83\/100/i)).toBeVisible();
  const historicalScore = page.getByText(/Score: 83\/100/i);
  await page.getByLabel("Purchase intent").selectOption("no");
  await page.getByLabel("Budget").selectOption("low");
  await expect(historicalScore).toBeVisible();
  const tomorrow = new Date(Date.now() + 86400000).toISOString().slice(0, 10);
  await page.getByLabel("Date").fill(tomorrow);
  await page.getByRole("button", { name: /preview callback/i }).click();
  await expect(page.getByText(/Callback proposed only for/i)).toBeVisible();
  await page.getByRole("button", { name: /preview callback/i }).click();
  await expect(page.getByText(/A callback preview already exists/i)).toBeVisible();
  await page.getByRole("button", { name: /stop \/ reset/i }).click();
  await expect(page.getByText(/Not yet qualified/i)).toBeVisible();
  await expect(interactionPicker).toHaveCount(0);
});
